// Generates js/web_manifest.js by walking disk.
// Maps lowercase path -> on-disk path (case-sensitive hosts need the real case).
// Usage: node gen_manifest.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(ROOT, 'js', 'web_manifest.js');

// Roots the original manifest covered. js/ is intentionally excluded (index.html
// loads those by exact path). mods/ is included so disk-placed mods are discovered.
const ROOTS = ['img', 'audio', 'maps', 'data', 'languages', 'modloader', 'movies', 'fonts', 'icon', 'mods'];
const ROOT_FILES = ['index.html', 'package.json', 'editor.json', 'game.rpgproject', 'steam_appid.txt'];
// Files that only exist at runtime (created by the loader) but must stay in the
// manifest so readdir/case-correction keeps working for them.
const PINNED = ['save/mods.json'];

const SKIP_DIRS = new Set(['.git', 'node_modules', '__pycache__']);

function walk(dir, rel, out) {
    let entries;
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch (e) { return; }
    for (const ent of entries) {
        if (ent.name.startsWith('.')) continue;
        const abs = path.join(dir, ent.name);
        const r = rel ? rel + '/' + ent.name : ent.name;
        if (ent.isDirectory()) {
            if (SKIP_DIRS.has(ent.name)) continue;
            walk(abs, r, out);
        } else if (ent.isFile()) {
            out.push(r);
        }
    }
}

const files = [];
for (const root of ROOTS) {
    const abs = path.join(ROOT, root);
    if (fs.existsSync(abs)) walk(abs, root, files);
}
for (const f of ROOT_FILES) {
    // Resolve true on-disk case (Windows is case-insensitive; manifest needs real case).
    const abs = path.join(ROOT, f);
    if (!fs.existsSync(abs)) continue;
    let real = f;
    try {
        const parent = path.dirname(abs);
        const base = path.basename(abs).toLowerCase();
        real = fs.readdirSync(parent).find(n => n.toLowerCase() === base) || f;
    } catch (e) { }
    files.push(real);
}
for (const p of PINNED) { files.push(p); }

// Build lowercase -> real path map. If two real paths collide on lowercase,
// keep the first (matches original behaviour of one entry per key).
const map = {};
let collisions = 0;
for (const rel of files) {
    const key = rel.toLowerCase();
    if (Object.prototype.hasOwnProperty.call(map, key) && map[key] !== rel) { collisions++; continue; }
    map[key] = rel;
}

const keys = Object.keys(map).sort();
let body = '// AUTO-GENERATED file map: lowercase path -> on-disk path (case-sensitive hosts).\n';
body += '// Regenerated by serve.mjs at startup so disk-placed mods in /mods/ are discovered.\n';
body += 'window.WEB_FILE_MANIFEST = {\n';
for (const k of keys) {
    body += '    ' + JSON.stringify(k) + ': ' + JSON.stringify(map[k]) + ',\n';
}
body += '};\n';

if (process.argv.includes('--check')) {
    // Compare against existing manifest: report keys lost / values changed.
    const cur = fs.readFileSync(OUT, 'utf8');
    const curMap = {};
    const re = /"([^"]+)"\s*:\s*"([^"]+)"/g;
    let m;
    while ((m = re.exec(cur)) !== null) { if (m[1] !== 'window.WEB_FILE_MANIFEST') curMap[m[1]] = m[2]; }
    const lost = Object.keys(curMap).filter(k => !map[k]);
    const changed = Object.keys(curMap).filter(k => map[k] && map[k] !== curMap[k]);
    console.log('existing keys:', Object.keys(curMap).length, '| new keys:', keys.length, '| collisions:', collisions);
    console.log('LOST keys:', lost.length);
    lost.slice(0, 40).forEach(k => console.log('  - ' + k));
    console.log('CHANGED values:', changed.length);
    changed.slice(0, 40).forEach(k => console.log('  ~ ' + k + ': ' + curMap[k] + ' -> ' + map[k]));
    console.log('ADDED keys:', keys.filter(k => !curMap[k]).length);
} else {
    fs.writeFileSync(OUT, body);
    console.log('Wrote ' + keys.length + ' entries to js/web_manifest.js (collisions: ' + collisions + ')');
}
